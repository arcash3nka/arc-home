// ══════════════════════════════════════════════════════════════════════════
//  АВАТАР — горящая сфера
//
//  Шар, объятый огнём. Не картинка и не спрайт: каждый кадр считается
//  заново из геометрии сферы и двух полей шума.
//
//  Устроено из двух слоёв:
//
//    корона   языки пламени вокруг шара. Вверх тянутся дальше, чем вниз —
//             жар поднимается. Шум берётся по углу, поэтому языки
//             обтекают шар по окружности, а не торчат во все стороны.
//    сфера    поверхность: слабое освещение по Ламберту, потемнение к краю
//             диска и текущий поверх шум. Форму держит именно потемнение;
//             один лямберт даёт освещённый мячик, а один шум — бесформенное
//             пятно, в котором шара не видно вовсе.
//
//  Цвет везде один и тот же — шкала жара: белое ядро, кремовое,
//  оранжевое, красное, пурпурное, синее к холодному краю.
//
//  Ячейка символа выше, чем шире (примерно 0.57), поэтому радиус по
//  горизонтали задан в колонках, а по вертикали делится на ASPECT —
//  иначе сфера выходит яйцом.
// ══════════════════════════════════════════════════════════════════════════

import { makeNoise } from './rng.js';

/** Шкала жара: от самого горячего к самому холодному. */
const HEAT = [
	'#ffffff', '#ffeec2', '#ffc46b', '#ff8a3c', '#ff4d5e',
	'#e8479f', '#c44fd8', '#8a4fe0', '#4a49dd', '#2a35b4', '#161b6e',
];
const WHITE = HEAT[0];

const RAMP = ['.', ':', '-', '=', '+', '*', '#', '%', '@'];

const ASPECT = 1.75;
const W = 64;
const H = 36;

const CX = W / 2 - 0.5;
const CY = H * 0.56;
const R = 20;                              // радиус в колонках

// свет сверху-слева-спереди, нормирован
const LX = -0.44, LY = -0.58, LZ = 0.69;

const surf = makeNoise(0x5eed);
const halo = makeNoise(0xbeef);

/** Индекс в шкале жара по величине 0..1. */
const heatColor = (v) => HEAT[Math.max(0, Math.min(HEAT.length - 1,
	Math.round((1 - v) * (HEAT.length - 1))))];

const glyph = (v) => RAMP[Math.max(0, Math.min(RAMP.length - 1,
	Math.floor(v * RAMP.length)))];

/**
 * @param {number} t время в секундах
 * @returns {{w:number,h:number,cells:Array<{x,y,ch,color,cls}>}}
 */
export function renderAvatar(t = 0) {
	const cells = [];

	for (let y = 0; y < H; y++) {
		for (let x = 0; x < W; x++) {
			const nx = (x - CX) / R;
			const ny = ((y - CY) * ASPECT) / R;
			const d = Math.hypot(nx, ny);

			let v = 0;

			if (d <= 1) {
				// ── поверхность сферы ────────────────────────────────────
				const z = Math.sqrt(Math.max(0, 1 - d * d));
				const lambert = Math.max(0, nx * LX + ny * LY + z * LZ);

				// шум в координатах поверхности: течёт вверх и слегка
				// заворачивается по глубине, поэтому шар выглядит объёмным,
				// а не оклеенным плоской текстурой
				const flow = surf(nx * 2.7 + z * 1.4 + 30, ny * 2.7 - t * 0.85);

				// Потемнение к краю диска — то же, что у настоящей звезды:
				// там луч зрения идёт по касательной сквозь более холодные
				// слои. Без него шар выглядит плоским пятном, а лямберт сам
				// по себе даёт освещённый мячик, а не горящую массу.
				const limb = 0.35 + z * 0.75;
				v = (0.40 + lambert * 0.55) * limb + flow * 0.42 - 0.12;
			} else {
				// ── корона ───────────────────────────────────────────────
				const out = d - 1;
				const up = Math.max(0, -ny);              // выше экватора
				// вверх языки длиннее, но не бесконечно: без ограничения
				// вокруг шара расползается дымка на пол-экрана
				const reach = 0.15 + Math.min(up, 1) * 0.45;
				if (out > reach) continue;

				const fall = Math.pow(1 - out / reach, 2);
				const ang = Math.atan2(ny, nx);
				// шум по углу — языки обтекают шар, а не торчат наружу
				// две гармоники по углу: крупные языки и рванина на них
				const turb = halo(ang * 5.0 + 12, out * 4.0 - t * 2.4) * 0.65
					+ halo(ang * 11.0 + 40, out * 7.0 - t * 3.6) * 0.35;

				// вычитаем порог прямо из шума: там, где он не дотянул,
				// пламени нет вовсе. Иначе вокруг шара висит ровная дымка,
				// а нужны отдельные языки
				v = fall * (turb * 1.85 - 0.58);
			}

			if (v <= 0.10) continue;

			const core = v > 0.93;
			cells.push({
				x, y,
				ch: glyph(Math.min(1, v)),
				color: core ? null : heatColor(Math.min(1, v)),
				cls: core ? 'av-flame av-core' : 'av-flame',
			});
		}
	}

	return { w: W, h: H, cells };
}

export function avatarToText(frame) {
	const grid = Array.from({ length: frame.h }, () => new Array(frame.w).fill(' '));
	for (const c of frame.cells) grid[c.y][c.x] = c.ch;
	return grid.map((r) => r.join('').replace(/\s+$/, '')).join('\n');
}
